"""Platform-neutral production scheduler.

Generates scheduling configurations for cron, Windows Task Scheduler,
and cloud one-shot runners. Does NOT run as an always-on process.

Usage::

    python -m src.scheduler --format cron
    python -m src.scheduler --format windows
    python -m src.scheduler --format cloud
    python -m src.scheduler --install cron

Supports:
    - Morning scan (daily after overnight data refresh)
    - Pre-game scan (30 min before each game window)
    - Post-game calibration (nightly)
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import platform
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


@dataclass
class ScheduleEntry:
    """A single scheduling entry."""
    name: str
    description: str
    cron_expression: str
    command: str
    working_directory: str
    enabled: bool = True

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "cron": self.cron_expression,
            "command": self.command,
            "working_directory": self.working_directory,
            "enabled": self.enabled,
        }


